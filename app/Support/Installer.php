    protected static function envValue(string $value): string
    {
        if ($value === '') {
            return '';
        }

        if (preg_match('/\s|#|"|\'|=/', $value)) {
            return '"'.str_replace(['\\', '"'], ['\\\\', '\\"'], $value).'"';
        }

        return $value;
    }

    public static function ensureEnvFile(): bool
    {
        $envPath = base_path('.env');

        if (! File::exists($envPath)) {
            File::put($envPath, self::defaultEnvContent([
                'APP_URL' => self::detectAppUrl(),
            ]));

            return true;
        }

        $content = File::get($envPath);

        if (! preg_match('/^DB_CONNECTION=/m', $content)) {
            $key = '';
            if (preg_match('/^APP_KEY=(.+)$/m', $content, $m)) {
                $key = trim($m[1]);
            }

            File::put($envPath, self::defaultEnvContent([
                'APP_KEY' => $key,
                'APP_URL' => self::detectAppUrl(),
            ]));
        }

        return true;
    }

    public static function detectAppUrl(): string
    {
        if (! empty($_SERVER['HTTP_HOST'])) {
            $scheme = (! empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
                || (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https')
                ? 'https'
                : 'http';

            return $scheme.'://'.$_SERVER['HTTP_HOST'];
        }

        return 'http://localhost';
    }

    /**
     * Write / update keys. Always merges recommended production defaults first,
     * then $values (so caller can override).
     *
     * @param  array<string, string>  $values
     */
    public static function writeEnv(array $values): void
    {
        self::ensureEnvFile();

        $envPath = base_path('.env');
        $content = File::get($envPath);

        $values = array_merge(self::recommendedEnvDefaults(), $values);

        foreach ($values as $key => $value) {
            $value = (string) $value;
            $formatted = self::envValue($value);

            if (preg_match("/^{$key}=.*/m", $content)) {
                $content = preg_replace(
                    "/^{$key}=.*/m",
                    "{$key}={$formatted}",
                    $content
                );
            } else {
                $content = rtrim($content)."\n{$key}={$formatted}\n";
            }
        }

        File::put($envPath, $content);
    }

    /**
     * Add any missing recommended keys without overwriting existing values.
     * Useful for upgrades of sites that already have a partial .env.
     */
    public static function ensureRecommendedKeys(): void
    {
        self::ensureEnvFile();

        $envPath = base_path('.env');
        $content = File::get($envPath);
        $defaults = self::recommendedEnvDefaults();
        $appended = false;

        foreach ($defaults as $key => $value) {
            if (preg_match("/^{$key}=/m", $content)) {
                continue;
            }
            $content = rtrim($content)."\n{$key}=".self::envValue((string) $value)."\n";
            $appended = true;
        }

        // Always force critical production safety + performance keys after install
        $force = [
            'APP_ENV' => 'production',
            'APP_DEBUG' => 'false',
            'LOG_LEVEL' => 'error',
            'CACHE_DRIVER' => 'file',
            'CACHE_STORE' => 'file',
            'SESSION_DRIVER' => 'database',
            'SESSION_LIFETIME' => '480',
            'SESSION_HTTP_ONLY' => 'true',
            'SESSION_SAME_SITE' => 'lax',
            'QUEUE_CONNECTION' => 'database',
            'SCOUT_DRIVER' => 'collection',
            'BROADCAST_DRIVER' => 'log',
            'FILESYSTEM_DISK' => 'local',
        ];

        foreach ($force as $key => $value) {
            $formatted = self::envValue((string) $value);
            if (preg_match("/^{$key}=.*/m", $content)) {
                $content = preg_replace("/^{$key}=.*/m", "{$key}={$formatted}", $content);
            } else {
                $content = rtrim($content)."\n{$key}={$formatted}\n";
            }
        }

        File::put($envPath, $content);

        if ($appended) {
            // no-op; kept for clarity
        }
    }

    /**
     * Apply full recommended .env after migrations (sessions/jobs tables exist).
     */
    public static function applyRecommendedEnv(): void
    {
        self::ensureRecommendedKeys();
        self::writeEnv(self::recommendedEnvDefaults());

        try {
            Artisan::call('config:clear');
        } catch (\Throwable) {
        }
    }

    /**
     * @deprecated Use applyRecommendedEnv()
     */
    public static function applyPerformanceEnv(): void
    {
        self::applyRecommendedEnv();
    }

    /**
     * Until migrations finish, never use database cache/sessions.
     * Laravel 11 reads CACHE_STORE (not only CACHE_DRIVER). A missing `cache`
     * or `sessions` table resets the wizard and throws on SiteSetting cache reads.
     */
    public static function ensureInstallSafeDrivers(): void
    {
        if (self::isInstalled()) {
            return;
        }

        self::ensureEnvFile();
        $envPath = base_path('.env');
        $content = File::get($envPath);
        $force = [
            'CACHE_DRIVER' => 'file',
            'CACHE_STORE' => 'file',
            'SESSION_DRIVER' => 'file',
            'QUEUE_CONNECTION' => 'sync',
        ];
        foreach ($force as $key => $value) {
            if (preg_match("/^{$key}=.*/m", $content)) {
                $content = preg_replace("/^{$key}=.*/m", "{$key}={$value}", $content);
            } else {
                $content = rtrim($content)."\n{$key}={$value}\n";
            }
        }
        File::put($envPath, $content);
    }

    public static function ensureAppKey(): string

    {
        self::ensureEnvFile();

        $envPath = base_path('.env');
        $content = File::get($envPath);

        if (preg_match('/^APP_KEY=(.+)$/m', $content, $m) && trim($m[1]) !== '') {
            return trim($m[1]);
        }

        $key = 'base64:'.base64_encode(random_bytes(32));
        self::writeEnv(['APP_KEY' => $key]);

        return $key;
    }

    public static function ensureStorageDirectories(): void
    {
        $dirs = [
            storage_path('app'),
            storage_path('app/public'),
            storage_path('framework'),
            storage_path('framework/cache'),
            storage_path('framework/cache/data'),
            storage_path('framework/sessions'),
            storage_path('framework/views'),
            storage_path('logs'),
            base_path('bootstrap/cache'),
        ];

        foreach ($dirs as $dir) {
            if (! is_dir($dir)) {
                @mkdir($dir, 0775, true);
            }
        }
    }

